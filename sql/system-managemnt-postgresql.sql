-- =========================================================
-- TIME SLOTS
-- =========================================================

CREATE TABLE tblTimeSlots (
    slot_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    slot_name VARCHAR(50),

    start_time TIME NOT NULL,
    end_time TIME NOT NULL,

    status room_status DEFAULT 'Active',

    CONSTRAINT uq_time_slot
        UNIQUE (start_time, end_time)
);


-- =========================================================
-- DAYS
-- =========================================================

CREATE TABLE tblDays (
    day_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    day_code VARCHAR(10) NOT NULL UNIQUE,
    day_name VARCHAR(50) NOT NULL,

    sort_order SMALLINT NOT NULL,

    is_active BOOLEAN DEFAULT TRUE
);


-- =========================================================
-- CLASSES
-- =========================================================

CREATE TABLE tblClasses (
    class_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    class_name VARCHAR(100),
    class_code VARCHAR(50) UNIQUE NOT NULL,

    course_id BIGINT NOT NULL,

   
    academic_year VARCHAR(9) NOT NULL,

    max_students INT DEFAULT 50,
    current_students INT DEFAULT 0,

    status VARCHAR(50) DEFAULT 'Active',

    CONSTRAINT fk_class_course
        FOREIGN KEY (course_id)
        REFERENCES tblCourses(course_id),

    CONSTRAINT fk_class_teacher
        FOREIGN KEY (teacher_id)
        REFERENCES tblEmployees(employee_id),

    CONSTRAINT fk_class_room
        FOREIGN KEY (room_id)
        REFERENCES tblRooms(room_id),

    CONSTRAINT fk_class_slot
        FOREIGN KEY (slot_id)
        REFERENCES tblTimeSlots(slot_id),

    CONSTRAINT chk_class_students
        CHECK (
            current_students >= 0
            AND max_students > 0
            AND current_students <= max_students
        )
);


-- =========================================================
-- TIMETABLES
-- =========================================================

CREATE TABLE tblTimetables (
    timetable_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    class_id BIGINT NOT NULL,
    day_id BIGINT NOT NULL,

    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_timetable_class
        FOREIGN KEY (class_id)
        REFERENCES tblClasses(class_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_timetable_day
        FOREIGN KEY (day_id)
        REFERENCES tblDays(day_id)
        ON DELETE CASCADE,

    CONSTRAINT uq_timetable
        UNIQUE (class_id, day_id)
);


-- =========================================================
-- ENROLLMENTS
