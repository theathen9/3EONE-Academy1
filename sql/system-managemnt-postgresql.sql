-- =========================================================
-- USER TOKENS
-- =========================================================

CREATE TABLE tblUserTokens (
    token_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id BIGINT NOT NULL,

    -- JWT ID (jti)
    jti UUID NOT NULL UNIQUE,

    access_expiry TIMESTAMP NOT NULL,

    -- SHA-256 hash of the raw refresh token
    refresh_token CHAR(64) NOT NULL UNIQUE,

    refresh_expiry TIMESTAMP NOT NULL,

    device_info VARCHAR(255),

    user_agent TEXT,

    ip_address VARCHAR(45),

    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    revoked_at TIMESTAMP NULL,

    CONSTRAINT fk_user_token_user
        FOREIGN KEY (user_id)
        REFERENCES tblUsers(user_id)
        ON DELETE CASCADE
);

