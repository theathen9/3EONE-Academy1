-- =========================================================
-- EMPLOYEE SUBJECTS
-- =========================================================

CREATE TABLE tblEmployeeSubjects (
    employee_subject_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    employee_id BIGINT NOT NULL,
    subject_id BIGINT NOT NULL,

    CONSTRAINT uq_employee_subject
        UNIQUE (employee_id, subject_id),

    CONSTRAINT fk_employee_subject_employee
        FOREIGN KEY (employee_id)
        REFERENCES tblEmployees(employee_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_employee_subject_subject
