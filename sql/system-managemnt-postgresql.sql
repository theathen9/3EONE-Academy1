-- =========================================================
-- BRANCHES
-- =========================================================

CREATE TABLE tblBranches (
    branch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_code VARCHAR(20) UNIQUE NOT NULL,
    branch_name VARCHAR(150) NOT NULL,
    phone1 VARCHAR(20),
    phone2 VARCHAR(20),
    email VARCHAR(150),
    address TEXT,
    location VARCHAR(20),
    status BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
-- =========================================================
-- ROOMS
-- =========================================================

CREATE TABLE tblRooms (
    room_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_name VARCHAR(50) NOT NULL,
    capacity INT NOT NULL,
    status VARCHAR(50) DEFAULT 'Active'
);


-- =========================================================
-- DEPARTMENTS
-- =========================================================

CREATE TABLE tblDepartments (
    department_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_code VARCHAR(20) UNIQUE NOT NULL,
    department_name VARCHAR(100) NOT NULL,
    description TEXT,
    status BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);


-- =========================================================
-- Positions
-- =========================================================

CREATE TABLE tblPositions (
    position_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    position_code VARCHAR(50) NOT NULL UNIQUE,
    position_name VARCHAR(150) NOT NULL UNIQUE,

    description TEXT,

    status BOOLEAN DEFAULT TRUE,

    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- =========================================================
-- EMPLOYEES
-- =========================================================

CREATE TABLE tblEmployees (
    employee_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    department_id BIGINT NULL,
    position_id BIGINT NULL,

    first_name_kh VARCHAR(100) NOT NULL,
    last_name_kh VARCHAR(100) NOT NULL,
    first_name_en VARCHAR(100) NOT NULL,
    last_name_en VARCHAR(100) NOT NULL,

    gender VARCHAR(20) NOT NULL,
    dob DATE NOT NULL,

    birth_village VARCHAR(100) NOT NULL,
    birth_commune VARCHAR(100) NOT NULL,
    birth_district VARCHAR(100) NOT NULL,
    birth_province VARCHAR(100) NOT NULL,

    curr_addr_village VARCHAR(100) NOT NULL,
    curr_addr_commune VARCHAR(100) NOT NULL,
    curr_addr_district VARCHAR(100) NOT NULL,
    curr_addr_province VARCHAR(100) NOT NULL,

    phone1 VARCHAR(20) NOT NULL,
    phone2 VARCHAR(20),

    email VARCHAR(150) UNIQUE,

    profile_image VARCHAR(255),

    hired_at DATE NOT NULL,

    status VARCHAR(20) DEFAULT 'Active',

    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_employee_department
        FOREIGN KEY (department_id)
        REFERENCES tblDepartments(department_id)
        ON DELETE SET NULL,

    CONSTRAINT fk_employee_position
        FOREIGN KEY (position_id)
        REFERENCES tblPositions(position_id)
        ON DELETE SET NULL
);

-- =========================================================
-- EMPLOYEE PLATFORMS
-- =========================================================

CREATE TABLE tblEmployeePositionHistory (
    position_history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    employee_id BIGINT NOT NULL,
    position_id BIGINT NOT NULL,
    department_id BIGINT NULL,

    start_date DATE NOT NULL,
    end_date DATE NULL,

    remarks TEXT,

    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NULL,

    CONSTRAINT fk_position_history_employee
        FOREIGN KEY (employee_id)
        REFERENCES tblEmployees(employee_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_position_history_position
        FOREIGN KEY (position_id)
        REFERENCES tblPositions(position_id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_position_history_department
        FOREIGN KEY (department_id)
        REFERENCES tblDepartments(department_id)
        ON DELETE SET NULL,

    CONSTRAINT fk_position_history_creator
        FOREIGN KEY (created_by)
        REFERENCES tblEmployees(employee_id)
        ON DELETE SET NULL,

    CONSTRAINT chk_position_history_dates
        CHECK (
            end_date IS NULL
            OR end_date >= start_date
        )
);


CREATE INDEX idx_position_history_employee
    ON tblEmployeePositionHistory(employee_id);

CREATE INDEX idx_position_history_department
    ON tblEmployeePositionHistory(department_id);

CREATE INDEX idx_position_history_dates
    ON tblEmployeePositionHistory(start_date, end_date);



